"""Run the EpiScope Bronze -> Silver -> Gold pipeline for one batch."""

import argparse
import json
import os
import re
from pathlib import Path

from pyspark.sql import SparkSession
from pyspark.sql import functions as F

from pipeline.bronze import ingest_bronze
from pipeline.silver import process_silver
from pipeline.gold import process_gold
from pipeline.incremental import (
    batch_is_complete,
    mark_batch_complete,
)


def run_pipeline(
    spark,
    input_dir: Path,
    lakehouse_dir: Path,
    batch_id: str,
    facilities_path: Path,
    ledger_path: Path,
    force: bool = False,
):
    if not re.fullmatch(r"[A-Za-z0-9_-]+", batch_id):
        raise ValueError("Invalid batch ID.")

    if batch_is_complete(ledger_path, batch_id) and not force:
        print(f"Batch {batch_id} is already marked complete. Skipping.")
        return {"batch_id": batch_id, "status": "skipped"}

    bronze_dir = lakehouse_dir / "bronze"
    silver_dir = lakehouse_dir / "silver"
    gold_dir = lakehouse_dir / "gold"

    # Step 1: Ingest source files into Bronze.
    ingest_bronze(spark, input_dir, bronze_dir, batch_id)

    # Step 2: Validate and transform the new batch into Silver.
    process_silver(spark, bronze_dir, silver_dir, batch_id)

    # Read the quality report generated by Silver.
    quality_path = (
        silver_dir / f"batch_id={batch_id}" / "quality_report.json"
    )
    quality = json.loads(quality_path.read_text(encoding="utf-8"))

    # Step 3: Identify the epidemiological weeks affected by this batch.
    silver_path = (
        silver_dir / f"batch_id={batch_id}" / "encounters"
    )
    silver = spark.read.parquet(str(silver_path))

    affected_weeks = [
        row["week_start"].isoformat()
        for row in (
            silver.select(
                F.to_date(
                    F.date_trunc(
                        "week",
                        F.to_date("onset_date"),
                    )
                ).alias("week_start")
            )
            .where(F.col("onset_date").isNotNull())
            .distinct()
            .collect()
        )
        if row["week_start"] is not None
    ]

    # Step 4: Recompute affected weeks using all available Silver batches.
    # The shared Gold output allows updated weeks to replace older partitions.
    if affected_weeks:
        process_gold(
            spark,
            silver_dir,
            gold_dir,
            batch_id,
            facilities_path,
            all_batches=True,
            affected_weeks=affected_weeks,
            shared_output=True,
        )
    else:
        print(
            f"Batch {batch_id} has no accepted Silver records. "
            "Gold recomputation is skipped."
        )

    # Step 5: Mark the batch complete only after successful processing.
    mark_batch_complete(
        ledger_path,
        batch_id,
        int(quality["input_rows"]),
        affected_weeks,
    )

    result = {
        "batch_id": batch_id,
        "status": "completed",
        "input_rows": quality["input_rows"],
        "silver_rows": quality["silver_rows"],
        "quarantined_rows": quality["quarantined_rows"],
        "affected_weeks": len(affected_weeks),
    }

    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, required=True)
    parser.add_argument("--lakehouse-dir", type=Path, required=True)
    parser.add_argument("--batch-id", required=True)
    parser.add_argument("--facilities-path", type=Path, required=True)
    parser.add_argument(
        "--ledger",
        type=Path,
        default=Path("data/lakehouse/processed_batches.json"),
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Rerun a batch even if the ledger marks it complete.",
    )
    args = parser.parse_args()

    if not os.environ.get("PATIENT_ID_SALT") or len(
        os.environ["PATIENT_ID_SALT"]
    ) < 32:
        parser.error(
            "Set PATIENT_ID_SALT to a secret of at least 32 characters."
        )

    spark = (
        SparkSession.builder
        .appName("EpiScope-Orchestration")
        .getOrCreate()
    )

    try:
        result = run_pipeline(
            spark=spark,
            input_dir=args.input_dir,
            lakehouse_dir=args.lakehouse_dir,
            batch_id=args.batch_id,
            facilities_path=args.facilities_path,
            ledger_path=args.ledger,
            force=args.force,
        )
        print(json.dumps(result, indent=2))
    finally:
        spark.stop()


if __name__ == "__main__":
    main()